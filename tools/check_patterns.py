# ── DepotKey RTTI ground-truth (§15, #19) ────────────────────────────────────
# The runtime (Rtti::ResolveVtableSlotBySignature) no longer trusts a hardcoded
# slot: it finds CConfigStore's vtable by RTTI, then DERIVES the accessor's slot
# by matching kDepotKeyFnPattern inside the vtable. Mirror that walk here so the
# cron confirms, per build, that the derivation resolves to EXACTLY ONE slot —
# and records which (a change from 6 = Valve reordered the vtable; the runtime
# handles it, but we want to see it). Zero or multiple => BLOCKING (the runtime
# primary path can't resolve uniquely; do not whitelist).
RTTI_DEPOTKEY = {"class": "12CConfigStore", "const": "kDepotKeyFnPattern",
                 "label": "DepotKey", "max_slots": 40}

# Name-derived resolution — the SECOND opinion, and the only one here that reads
# no byte of the target function. Mirrors Rtti::ResolveVtableSlotByName (and
# download.lua): find the slot of the interface-MAP class whose function
# references the method name as a string, then apply that index to the concrete
# class. Verified on build bc54101b29 by tools/experiment_ifacemap_slot.py:
# "GetBinary" -> map slot 6 -> CConfigStore 0x11a4500, the pattern's own answer.
#
# Why it belongs in CI: the runtime uses it as its last-resort resolver, and a
# resolver nothing validates is a parachute nobody has opened. It is also what
# makes `agrees_with_pattern` mean something — that field compares the pattern
# with itself, so it is true by construction and reports nothing.
BYNAME_DEPOTKEY = {"map_class": "21IClientConfigStoreMap", "method": "GetBinary",
                   "impl_class": "12CConfigStore", "label": "DepotKey-byname",
                   "max_slots": 64,
                   # Max distance from a slot's entry for a reference to count as
                   # "inside it". The same name is referenced from unrelated code
                   # far from this vtable; attributing that would pick a wrong slot.
                   "max_fn_size": 512}

# GMRC's RESCUE path, which nothing validated until now — and a rescue only runs
# once the pattern has already missed, i.e. exactly when there is no second
# opinion left to catch it being wrong. Two things the Deck depends on here:
#
#   (a) the job-name string anchor: it must exist and be referenced from EXACTLY
#       ONE site, or it identifies nothing (the v0.10.3 LoadPackage lesson);
#   (b) .eh_frame_hdr: since 2026-09-07 the runtime turns that site into the
#       function ENTRY by looking it up in the binary's own sorted function table
#       (src/eh_frame.hpp) instead of walking backwards. A build whose header
#       encodings this parser does not implement makes the runtime fail closed and
#       fall back to the walk-back and its two documented failure modes — silently,
#       unless CI says so.
GMRC_XREF = {"string": "ContentServerDirectory.GetManifestRequestCode#1",
             "const": "kGmrcFunctionPattern", "label": "GMRC"}

# ── finder anchors (§13.5) — mirrored from package_zero_finder.cpp ────────────
# (a) cache-access idiom, anchored on the 0xc58 tree-root offset of
#     CPackageInfoCache:  lea r1,[GOT+X] ; mov r2,[r1] ; mov r3,[r2+0xc58].
#     The 0xc58 disp32 little-endian (58 0C 00 00) is the unambiguous needle;
#     we validate the lea/mov/mov shape backwards from each hit.
# (b) GMRC prologue tail that survives the hook detour — the bytes DeriveGotBase
#     scans for.
CACHE_ROOT_OFFSET = 0xC58
CACHE_IDIOM_NEEDLE = "58 0C 00 00"
GMRC_PROLOGUE_TAIL = "55 89 E5 57 56 53 81 EC 10 01 00 00 8B 7D 08 8B 4D 20"


# ── patterns.hpp parsing ─────────────────────────────────────────────────────

def parse_patterns_hpp(path):
    """Extract {constant_name: "byte pattern"} for every kXxxPattern in the
    header. The decls look like:
        inline constexpr const char* kDepotKeyFnPattern =
            "55 57 56 ...";
    so we match the name and the (possibly next-line) string literal."""
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    out = {}
    for m in re.finditer(r'(\bk\w+Pattern)\s*=\s*"([0-9A-Fa-f? ]+)"', text):
        out[m.group(1)] = m.group(2).strip()
    return out


# ── ELF: executable segments ─────────────────────────────────────────────────

def load_exec_segments(path):
    """Return [(vaddr, bytes), ...] for every PT_LOAD|PF_X segment of a 32-bit
    little-endian ELF. vaddr is the segment's p_vaddr, which for a shared object
    (image base 0) IS the RVA base — so a match at byte offset `o` within the
    segment has RVA = vaddr + o, matching derive_patterns.py's RVA reporting."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"\x7fELF":
        raise ValueError("not an ELF file")
    ei_class, ei_data = data[4], data[5]
    if ei_class != 1:
        raise ValueError("not ELFCLASS32 (steamclient.so is 32-bit)")
    if ei_data != 1:
        raise ValueError("not little-endian")
    # Elf32_Ehdr: e_phoff@0x1C(4), e_phentsize@0x2A(2), e_phnum@0x2C(2)
    e_phoff = struct.unpack_from("<I", data, 0x1C)[0]
    e_phentsize = struct.unpack_from("<H", data, 0x2A)[0]
    e_phnum = struct.unpack_from("<H", data, 0x2C)[0]
    PT_LOAD, PF_X = 1, 0x1
    segs = []
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        # Elf32_Phdr: p_type(0) p_offset(4) p_vaddr(8) ... p_filesz(16) p_flags(24)
        p_type, p_offset, p_vaddr = struct.unpack_from("<III", data, off)
        p_filesz = struct.unpack_from("<I", data, off + 16)[0]
        p_flags = struct.unpack_from("<I", data, off + 24)[0]
        if p_type == PT_LOAD and (p_flags & PF_X):
            segs.append((p_vaddr, data[p_offset:p_offset + p_filesz]))
    if not segs:
        raise ValueError("no executable PT_LOAD segment found")
    return segs


# ── byte-pattern scanning ────────────────────────────────────────────────────

def pattern_to_regex(patstr):
    """Compile a 'AA BB ?? CC' pattern into a bytes regex: concrete bytes are
    escaped literally, '??' becomes '.'. DOTALL is essential so a wildcard can
    match a 0x0A byte (without it, '.' would skip newlines and miss matches)."""
    parts = []
    for tok in patstr.split():
        if tok.startswith("?"):
            parts.append(b".")
        else:
            parts.append(re.escape(bytes([int(tok, 16)])))
    return re.compile(b"".join(parts), re.DOTALL)


def scan_rvas(segments, patstr):
    """Return the list of RVAs where `patstr` matches across all exec segments.
    Patterns are long, distinctive prologues, so non-overlapping finditer is
    sufficient (overlaps are not a real concern at 28+ bytes)."""
    rx = pattern_to_regex(patstr)
    hits = []
    for vaddr, buf in segments:
        for m in rx.finditer(buf):
            hits.append(vaddr + m.start())
    return hits


def verify_cache_idiom(segments):
    """Find every valid cache-access idiom and return [(rva, lea_disp32), ...].
    For each `58 0C 00 00` needle the layout backwards is:
        base+0 = 8D (lea r1,[GOT+disp32])   base+2..5 = disp32
        base+6 = 8B (mov r2,[r1])
        base+8 = 8B (mov r3,[r2+0xc58])      base+10 = 58 0C 00 00 (the needle)
    so base = needle_off - 10. Validate the 8D/8B/8B shape before accepting."""
    needle = bytes(int(t, 16) for t in CACHE_IDIOM_NEEDLE.split())
    out = []
    for vaddr, buf in segments:
        start = 0
        while True:
            o = buf.find(needle, start)
            if o < 0:
                break
            start = o + 1
            base = o - 10
            if base < 0:
                continue
            if buf[base] == 0x8D and buf[base + 6] == 0x8B and buf[base + 8] == 0x8B:
                disp = struct.unpack_from("<i", buf, base + 2)[0]
                out.append((vaddr + base, disp))
    return out


