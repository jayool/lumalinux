def emit_rvas_file(result, out_dir, steam_version):
    """Write <out_dir>/<sha256>.yaml with the RVAs check_patterns already derived
    — one file per build, keyed by hash, mirroring steam-monitor's <sha256>.toml
    layout. The runtime resolver consumes these RVA-first (docs/rva-feed-design.md);
    src/patterns.hpp stays the fallback. Only UNIQUE, non-diagnostic hooks are
    written (a moved/ambiguous hook is omitted so that hook falls back to its byte
    pattern). Hand-serialized for a stable, diff-friendly, dependency-free output.
    Caller must gate on a non-BLOCKING verdict."""
    os.makedirs(out_dir, exist_ok=True)
    sha = result["steamclient_sha256"]

    hook_lines = []
    for label, info in result["hooks"].items():          # insertion order = stable
        if info.get("tier") == "diagnostic":
            continue
        if info.get("status") == "UNIQUE" and info.get("rvas"):
            hook_lines.append('  %s: "%s"' % (label, info["rvas"][0]))

    out = [
        "# Auto-generated by tools/check_patterns.py --emit-rvas. Do NOT edit by hand.",
        "# Per-build hook RVAs (file vaddrs) keyed by steamclient.so SHA-256,",
        "# consumed RVA-first by the runtime resolver (docs/rva-feed-design.md).",
        "# Byte patterns in src/patterns.hpp remain the fallback.",
        'steamclient_sha256: "%s"' % sha,
    ]
    if steam_version:
        out.append("steam_version: %s" % steam_version)
    out.append("hooks:" if hook_lines else "hooks: {}")
    out.extend(hook_lines)

    rt = result.get("rtti", {})
    if rt.get("status") == "UNIQUE":
        out += ["depotkey_rtti:",
                '  class: "%s"' % rt["class"],
                "  slot: %d" % rt["slot"],
                '  rva: "%s"' % rt["rva"]]

    ci = result.get("finder", {}).get("cache_idiom", {})
    if ci.get("status") == "PRESENT" and ci.get("sites"):
        out += ["finder:",
                '  cache_global_disp: "%s"' % ci["sites"][0]["disp32"]]

    path = os.path.join(out_dir, sha + ".yaml")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    return path

